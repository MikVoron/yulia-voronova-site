-- Пересчёт КБЖУ и клетчатки для рецепта "Соус из кешью" (cashew-sauce)
-- Методика: расчёт от состава ингредиентов по USDA FoodData Central (ТЗ от 2026-04-18)
--
-- Состав (382,5 г готового):
--   кешью сырой 200 г, вода 150 мл, чеснок ~4,5 г (1,5 зубчика),
--   сок 1/2 лимона ~25 г, соль 3 г (КБЖУ=0).
--
-- Источники USDA: cashew raw (170162), garlic raw (169230), lemon juice (167747).
--
-- На 100 г готового: 292,3 ккал / 9,6 Б / 22,9 Ж / 16,6 У / 1,8 клетчатка
-- На порцию 15 г (25 порций): 44 ккал / 1,4 Б / 3,4 Ж / 2,5 У / 0,3 клетчатка
--
-- Было: 70 / 2 / 5 / 5 / 0,5 (завышено ~в 1,6 раза — 467 ккал/100 г, нереально для соуса с 40% воды).

BEGIN;

UPDATE recipes
SET
  kcal    = 44,
  protein = 1.4,
  fat     = 3.4,
  carbs   = 2.5,
  fiber   = 0.3
WHERE id = 'cashew-sauce';

COMMIT;

-- Проверка
SELECT id, name, kcal, protein, fat, carbs, fiber, portion_grams, servings
FROM recipes
WHERE id = 'cashew-sauce';
