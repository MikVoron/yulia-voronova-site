-- Салат из запечённой свёклы, белой фасоли и рукколы.
-- Карточка покажет: «15–20 мин» и отдельное уточнение «↳ без запекания и варки».
-- Полная страница рецепта выводит это же уточнение под временем.
-- Безопасно для повторного запуска.

UPDATE recipes
SET
  time_min = 15,
  time_label = '15–20 минут (без запекания и варки)',
  updated_at = now()
WHERE id = 'beetroot-bean-arugula';
